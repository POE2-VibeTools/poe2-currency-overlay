// i18n-game-names.mjs - derive localized CURRENCY names from the vendored parser data.
//
//   node scripts/i18n-game-names.mjs
//
// The price feed (poe2scout) only ever gives us English names, but a Russian player's
// stash, currency exchange and trade site are all Russian - showing them "Exalted Orb"
// makes them translate in their head. The parser data we already ship carries both
// spellings per item:
//     {"name": "Сфера возвышения", "refName": "Exalted Orb", ...}
// so the localized name is DERIVED from GGG's own strings, never AI-translated. That
// matters: a currency name has to match what the player sees in game exactly.
//
// Scope is deliberately narrow - category "Currency" only (a few hundred entries, a few
// KB per language). Item and mod text already arrives in the player's language from
// their own clipboard, so it needs nothing here.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.join(HERE, "..", "renderer", "vendor", "ee2", "data");
const OUT = path.join(HERE, "..", "renderer", "i18n");
const LANGS = ["ru", "pt", "de", "fr", "es"];

// Everything the price feed can name in the Currency tab, Net Worth or a price check -
// i.e. stackable, tradeable things, not gear. Omens were the miss that surfaced this:
// they are their own category, so "Omen of Chaotic Quantity" stayed English while the
// orbs around it translated.
const TRADEABLE = new Set([
  "Currency", "Omen", "SoulCore", "MapFragment", "PinnacleKey", "VaultKey", "Breachstone",
  "ExpeditionLogbook", "MiscMapItem", "TowerAugment", "Incubator", "BrequelFruit", "Relic",
  "Map", // waystones
]);

function currencyNames(lang) {
  const file = path.join(DATA, lang, "items.ndjson");
  if (!fs.existsSync(file)) return null;
  const map = {};
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    if (!line) continue;
    let j;
    try { j = JSON.parse(line); } catch { continue; }
    const cat = j.craftable && j.craftable.category;
    if (!TRADEABLE.has(cat)) continue;
    // refName is the English canonical; name is this language's spelling
    if (j.refName && j.name && j.name !== j.refName) map[j.refName] = j.name;
  }
  return map;
}

const all = {};
for (const lang of LANGS) {
  const m = currencyNames(lang);
  if (!m) { console.log(`${lang}: no data vendored, skipped`); continue; }
  all[lang] = m;
  console.log(`${lang}: ${Object.keys(m).length} names`);
}

const body = Object.entries(all)
  .map(([lang, m]) => `window.I18N_NAMES.${lang} = ${JSON.stringify(m, null, 2)};`)
  .join("\n");

fs.writeFileSync(path.join(OUT, "game-names.js"),
  "'use strict';\n"
  + "// GENERATED by scripts/i18n-game-names.mjs - do not hand-edit.\n"
  + "// English currency name -> the name GGG uses in that language, lifted from the\n"
  + "// vendored parser data. Not a translation: these are the game's own strings, so they\n"
  + "// match what the player sees in their stash and on the trade site.\n"
  + "window.I18N_NAMES = window.I18N_NAMES || {};\n"
  + body + "\n");

const size = fs.statSync(path.join(OUT, "game-names.js")).size;
console.log(`game-names.js: ${(size / 1024).toFixed(1)} KB`);
console.log("sample:", JSON.stringify({
  ru: all.ru && all.ru["Exalted Orb"], de: all.de && all.de["Exalted Orb"],
  fr: all.fr && all.fr["Divine Orb"], pt: all.pt && all.pt["Chaos Orb"],
}));
