'use strict';
// Bake the set of rune-scope stat ids whose stat has a "Bonded:" TWIN in GGG's
// live /api/trade2/data/stats.
//
//   node dev/build-bonded-ids.js <ggg-stats.json>
//
// Why this list exists: trade's rune_sockets (Augmentable Sockets) EXCLUDES a
// socket bound by a unique soul-core-alike (Uhtred's Sidereus: 3 visible sockets
// index as 2 - verified by a user's search and our own probes) but COUNTS a
// socket holding a bonded league rune (a 1-socket helm with a Bonded fill matches
// rune_sockets>=1 - probed live). The two are indistinguishable in EE2's data
// (both categorised SoulCore); GGG's dict tells them apart: every bonded-capable
// stat carries a "Bonded: <text>" twin entry, the excluded ones don't.
// Output: renderer/item/bonded-rune-ids.js (window.BondedRuneIds).
const fs = require('fs');
const path = require('path');

const data = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const entries = [];
for (const g of data.result || []) for (const e of g.entries || []) entries.push(e);

const norm = (s) => String(s || '').replace(/\s+/g, ' ').trim().toLowerCase();
const runeByText = new Map();
for (const e of entries) {
  if (e.id.startsWith('rune.') && !/^Bonded:/.test(e.text)) runeByText.set(norm(e.text), e.id);
}
const out = new Set();
for (const e of entries) {
  const m = /^Bonded:\s*(.*)$/s.exec(e.text || '');
  if (!m) continue;
  const twin = runeByText.get(norm(m[1]));
  if (twin) out.add(twin);
}
const ids = [...out].sort();
const file = path.join(__dirname, '..', 'renderer', 'item', 'bonded-rune-ids.js');
const header = '// GENERATED by dev/build-bonded-ids.js against GGG\'s live /api/trade2/data/stats.\n'
  + '// Rune-scope stat ids that have a "Bonded:" twin - i.e. can come from a bonded\n'
  + '// league rune, whose socket trade\'s rune_sockets DOES count. Sockets bound by a\n'
  + '// soul-core-alike with no Bonded twin (Uhtred\'s Sidereus) are the ones it\n'
  + '// excludes. Rebake when GGG adds stats.\n';
fs.writeFileSync(file, header + 'window.BondedRuneIds = ' + JSON.stringify(ids, null, 1) + ';\n');
console.log(ids.length + ' bonded-capable rune ids -> ' + file);
